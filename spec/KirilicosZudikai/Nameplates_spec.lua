-- Kirilicos Žudikai: alerts and skulls for nearby Cyrillic-named enemies.

local S = dofile("spec/KirilicosZudikai/support.lua")
local M = S.M
local ALERT_SOUND = 12197 -- SOUNDKIT.RAID_BOSS_EMOTE_WARNING in the fake client

local KZ

local function session(keepSaved, extra)
    KZ = S.session(keepSaved, extra)
    return KZ
end

describe("nearby Cyrillic enemies", function()
    it("puts a skull on the nameplate and alerts", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач", "WARRIOR", 40)
        local plate = M.AddPlate("nameplate1", S.V1)
        local skull = KZ.SkullFor("nameplate1")
        assert.truthy(skull)
        assert.are.equal(plate, skull.parent)
        assert.is_true(skull.shown)
        assert.are.equal(1, #M.raidWarnings)
        S.contains(M.raidWarnings[1], "Борис Бородач")
        S.contains(M.raidWarnings[1], "40 Warrior")
        S.contains(M.ChatText(), "Cyrillic enemy nearby")
        assert.are.equal(ALERT_SOUND, M.soundKits[#M.soundKits])
    end)

    it("alerts for the same player only once within the cooldown", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        M.RemovePlate("nameplate1")
        M.Advance(60)
        M.AddPlate("nameplate2", S.V1)
        assert.truthy(KZ.SkullFor("nameplate2"))
        assert.are.equal(1, #M.raidWarnings)
        M.RemovePlate("nameplate2")
        M.Advance(241)
        M.AddPlate("nameplate3", S.V1)
        assert.are.equal(2, #M.raidWarnings)
    end)

    it("uses the alert time from the settings", function()
        session()
        KZ.SetOption("alertCooldown", 1)
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        M.RemovePlate("nameplate1")
        M.Advance(61)
        M.AddPlate("nameplate2", S.V1)
        assert.are.equal(2, #M.raidWarnings)
    end)

    it("leaves out own-faction players, Latin names and NPCs", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач", nil, nil, { faction = "Horde", enemy = false })
        S.addPlayer(S.V2, "Mary Smith")
        S.addPlayer("Creature-0-1-2-3-4-5", "Злой Волк", nil, nil, { npc = true })
        M.AddPlate("nameplate1", S.V1)
        M.AddPlate("nameplate2", S.V2)
        M.AddPlate("nameplate3", "Creature-0-1-2-3-4-5")
        assert.is_nil(KZ.SkullFor("nameplate1"))
        assert.is_nil(KZ.SkullFor("nameplate2"))
        assert.is_nil(KZ.SkullFor("nameplate3"))
        assert.are.equal(0, #M.raidWarnings)
    end)

    it("falls back to 'is an enemy' when the faction is unknown", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач", nil, nil, { faction = false, enemy = true })
        S.addPlayer(S.V2, "Глеб Грибов", nil, nil, { faction = false, enemy = false })
        M.AddPlate("nameplate1", S.V1)
        M.AddPlate("nameplate2", S.V2)
        assert.truthy(KZ.SkullFor("nameplate1"))
        assert.is_nil(KZ.SkullFor("nameplate2"))
    end)

    it("takes the skull off when the nameplate goes, and reuses it", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        local skull = KZ.SkullFor("nameplate1")
        M.RemovePlate("nameplate1")
        assert.is_nil(KZ.SkullFor("nameplate1"))
        assert.is_false(skull.shown)
        S.addPlayer(S.V2, "Глеб Грибов")
        M.AddPlate("nameplate1", S.V2)
        assert.are.equal(skull, KZ.SkullFor("nameplate1"))
    end)

    it("leaves nameplates the game keeps from addons alone", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1, { forbidden = true })
        assert.is_nil(KZ.SkullFor("nameplate1"))
        assert.are.equal(1, KZ.plateStats.forbidden)
        assert.are.equal(1, #M.raidWarnings) -- the alert does not need the nameplate
    end)

    it("skips a player whose name the game hides", function()
        session()
        M.players[S.V1] = { name = M.SECRET, unitName = M.SECRET, faction = "Alliance", enemy = true }
        M.AddPlate("nameplate1", S.V1)
        assert.is_nil(KZ.SkullFor("nameplate1"))
        assert.are.equal(0, #M.raidWarnings)
        assert.are.equal(1, KZ.plateStats.hidden)
    end)

    it("ignores a hidden nameplate token without errors", function()
        session()
        M.Fire("NAME_PLATE_UNIT_ADDED", M.SECRET)
        M.Fire("NAME_PLATE_UNIT_REMOVED", M.SECRET)
        assert.are.equal(0, #M.raidWarnings)
    end)

    it("shows skulls but no alerts in battlegrounds, unless switched on", function()
        session()
        M.instanceType = "pvp"
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        assert.truthy(KZ.SkullFor("nameplate1"))
        assert.are.equal(0, #M.raidWarnings)
        assert.are.equal(0, M.sounds)
        KZ.SetOption("alertInBattlegrounds", true)
        S.addPlayer(S.V2, "Глеб Грибов")
        M.AddPlate("nameplate2", S.V2)
        assert.are.equal(1, #M.raidWarnings)
    end)

    it("/kz skull takes skulls off and puts them back without new alerts", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        SlashCmdList.KIRILICOSZUDIKAI("skull")
        assert.is_false(KZ.settings.skull)
        assert.is_nil(KZ.SkullFor("nameplate1"))
        S.addPlayer(S.V2, "Глеб Грибов")
        M.AddPlate("nameplate2", S.V2)
        assert.is_nil(KZ.SkullFor("nameplate2"))
        SlashCmdList.KIRILICOSZUDIKAI("skull")
        assert.truthy(KZ.SkullFor("nameplate1"))
        assert.truthy(KZ.SkullFor("nameplate2"))
        assert.are.equal(2, #M.raidWarnings)
    end)

    it("/kz alert stops alerts but keeps skulls", function()
        session()
        SlashCmdList.KIRILICOSZUDIKAI("alert")
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        assert.truthy(KZ.SkullFor("nameplate1"))
        assert.are.equal(0, #M.raidWarnings)
    end)

    it("plays no alert sound when that is switched off", function()
        session()
        KZ.SetOption("alertSound", false)
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        assert.are.equal(1, #M.raidWarnings)
        assert.are.equal(0, M.sounds)
    end)

    it("clears skulls on a loading screen", function()
        session()
        S.addPlayer(S.V1, "Борис Бородач")
        M.AddPlate("nameplate1", S.V1)
        M.Fire("PLAYER_ENTERING_WORLD")
        assert.is_nil(KZ.SkullFor("nameplate1"))
    end)

    it("shows a sample alert in /kz test", function()
        session()
        SlashCmdList.KIRILICOSZUDIKAI("test")
        assert.are.equal(1, #M.raidWarnings)
        S.contains(M.raidWarnings[1], "(test)")
    end)
end)
